export function matchesChip(video: Video, chip: Chip) {
  switch (chip) {
    case "All":
      return !video.topic;
    case "New releases":
      return Boolean(video.newRelease);
    case "Spoiler-free":
      return Boolean(video.spoilerFree);
    case "Top rated":
      return Boolean(video.topRated);
    default:
      return video.genre === chip && !video.topic;
  }
}

